export type MessageKey = keyof typeof messages['zh-CN']

export function normalizeUiLanguage(value: string | undefined | null): UiLanguage {
  if (value === 'en' || value === 'ja-JP' || value === 'zh-CN') return value
  if (value?.startsWith('ja')) return 'ja-JP'
  if (value?.startsWith('en')) return 'en'
  return 'zh-CN'
}

export function createTranslator(language: UiLanguage) {
  const dictionary = messages[normalizeUiLanguage(language)] ?? messages['zh-CN']
  return (key: MessageKey, vars?: Record<string, string | number>): string => {
    let value: string = dictionary[key] ?? messages['zh-CN'][key]
    if (vars) {
      for (const [name, replacement] of Object.entries(vars)) {
        value = value.replaceAll('{' + name + '}', String(replacement))
      }
    }
    return value
  }
}

export function formatRelativeTime(value: string, language: UiLanguage) {
  const t = createTranslator(language)
  const delta = Math.max(0, Date.now() - new Date(value).getTime())
  if (delta < 60_000) return t('justNow')
  if (delta < 3_600_000) return t('minutesAgo', { count: Math.floor(delta / 60_000) })
  if (delta < 86_400_000) return t('hoursAgo', { count: Math.floor(delta / 3_600_000) })
  const locale = language === 'en' ? 'en' : language === 'ja-JP' ? 'ja-JP' : 'zh-CN'
  return new Intl.DateTimeFormat(locale, { month: 'short', day: 'numeric' }).format(new Date(value))
}

export function formatAbsoluteTime(value: string, language: UiLanguage) {
  const locale = language === 'en' ? 'en' : language === 'ja-JP' ? 'ja-JP' : 'zh-CN'
  return new Intl.DateTimeFormat(locale, { month: 'long', day: 'numeric', hour: '2-digit', minute: '2-digit' }).format(new Date(value))
}
